#!/usr/bin/env bash
# Turn the current project into a Video Editor agent workspace. Run it from the project root right
# after installing the skill, however it was installed (git clone, npx skills, Codex skill-installer…).
#
#   setup.sh                  write AGENTS.md + CLAUDE.md, create the workspace, link the skill
#   setup.sh --no-link        skip linking the skill into .claude/, .agents/ and .opencode/
#
# Safe to rerun. AGENTS.md is managed between <!-- video-editor:begin/end --> markers, so an
# existing AGENTS.md keeps its own content. Then run doctor.sh and follow AGENTS.md.
set -uo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

LINK=1
for arg in "$@"; do
  case "$arg" in
    --no-link) LINK=0 ;;
    -h|--help) sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

ROOT="$PROJECT_ROOT"
# Some installers drop the executable bit; restore it so scripts can be called directly.
chmod +x "$SKILL_DIR"/scripts/*.sh "$SKILL_DIR"/scripts/*.py "$SKILL_DIR"/scripts/reel/*.py 2>/dev/null || true
# Path the instructions use to reach the skill: relative when it lives inside the project.
case "$SKILL_DIR/" in
  "$ROOT"/*) SKILL_REF="$(python3 -c 'import os, sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "$SKILL_DIR" "$ROOT")" ;;
  *) SKILL_REF="$SKILL_DIR" ;;
esac
echo "setup: project $ROOT"
echo "setup: skill   $SKILL_REF"

# ---------------------------------------------------------------- AGENTS.md
BEGIN='<!-- video-editor:begin — generated by video-editor/scripts/setup.sh; edit the template, not this block -->'
END='<!-- video-editor:end -->'
block="$(sed "s#{{SKILL_DIR}}#$SKILL_REF#g" "$SKILL_DIR/templates/AGENTS.md")"
agents="$ROOT/AGENTS.md"
python3 - "$agents" "$BEGIN" "$END" "$block" <<'PY'
import re, sys
from pathlib import Path
path, begin, end, block = Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
managed = f"{begin}\n{block.rstrip()}\n{end}\n"
if not path.exists():
    path.write_text(managed, encoding="utf-8"); print("setup: wrote AGENTS.md")
else:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(begin.split(" —")[0]) + r".*?" + re.escape(end) + r"\n?", re.S)
    if pattern.search(text):
        path.write_text(pattern.sub(lambda _: managed, text, count=1), encoding="utf-8"); print("setup: refreshed the Video Editor block in AGENTS.md")
    else:
        path.write_text(text.rstrip() + "\n\n" + managed, encoding="utf-8"); print("setup: appended the Video Editor block to the existing AGENTS.md")
PY

# ---------------------------------------------------------------- CLAUDE.md
claude="$ROOT/CLAUDE.md"
if [ ! -f "$claude" ]; then
  printf '@AGENTS.md\n' > "$claude" && echo "setup: wrote CLAUDE.md (imports AGENTS.md)"
elif ! grep -qx '@AGENTS.md' "$claude"; then
  printf '\n@AGENTS.md\n' >> "$claude" && echo "setup: added @AGENTS.md to CLAUDE.md"
fi

# ---------------------------------------------------------------- .gitignore
gi="$ROOT/.gitignore"
added=""
for entry in .env jobs/; do
  if [ ! -f "$gi" ] || ! grep -qxF "$entry" "$gi"; then echo "$entry" >> "$gi"; added="$added $entry"; fi
done
[ -n "$added" ] && echo "setup: .gitignore +$added (secrets and job media stay out of git)"

# ---------------------------------------------------------------- workspace + links
python3 "$SKILL_DIR/scripts/workspace.py" init
[ "$LINK" = 1 ] && bash "$SKILL_DIR/scripts/link.sh" --project "$ROOT"

cat <<EOF

setup: done. Next — as the agent, now:
  1. bash $SKILL_REF/scripts/doctor.sh
  2. follow the "Session start" section of AGENTS.md: brand interview, missing connections, environment.
EOF
